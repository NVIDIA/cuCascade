/**
 * @file test_tls_record_layer.cpp
 * @brief The key schedule and the built-in receive record layer (tier 2) in isolation, ported
 * from gpuio `tests/unit/net/test_tls_record_rx.cpp`:
 *  - key schedule: RFC 8448 §3/§4 traffic keys, "traffic upd", SHA-384, TLS 1.2 PRF and key
 *    block (reference values computed with an independent HMAC implementation);
 *  - record protection: the RFC 8448 server/client records (ticket skipped, data delivered,
 *    close_notify), at every wrap point and every arrival split, tampering at every byte;
 *  - records sealed by the test with known keys (EVP directly): TLS 1.3 padding, inner types,
 *    fragmented / interleaved handshake messages, KeyUpdate rules, alerts, header limits,
 *    sequence overflow; TLS 1.2 explicit nonces, HelloRequest, alerts, limits;
 *  - streams generated by OpenSSL in process (socketpair handshake through the provider's
 *    session + `export_keys`; the server then writes into a memory BIO): TLS 1.3 and 1.2,
 *    AES-128/256-GCM, record padding, tickets, KeyUpdate requested / not, odd sizes;
 *  - a split-point fuzzer (every wrap point, every arrival split, random chunking through a
 *    wrapping ring with random scattered windows, guard bytes checked);
 *  - the F3 caps and F4 window wiping of gpuio's security review.
 * gpuio's allocation-counter test is not ported: it replaces operator new and OpenSSL's memory
 * functions process-wide, which cannot live in the shared test binary.
 */


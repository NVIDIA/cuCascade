/// A scripted server stream: odd sizes, max-size records, tickets and KeyUpdates (TLS 1.3).
struct script_counts {
  unsigned tickets{0};
  unsigned key_updates{0};
  unsigned requested{0};
};
script_counts run_script(tls_pair& p, bool tls13, bool big)
{
  script_counts c{};
  if (tls13) { c.tickets = 2; }  // num_tickets at the handshake
  std::uint64_t seed        = 1;
  std::size_t const sizes[] = {1, 2, 7, 100, 511, 512, 513, 700, 1500, 3000, 17, 4001};
  for (std::size_t const n : sizes) {
    p.write(n, seed++);
  }
  if (tls13) {
    p.ticket();
    ++c.tickets;
    p.write(333, seed++);
    p.key_update(false);
    ++c.key_updates;
    p.write(2049, seed++);
    p.key_update(true);
    ++c.key_updates;
    ++c.requested;
    p.write(5, seed++);
  }
  if (big) {
    p.write(16384, seed++);
    p.write(16385, seed++);
    p.write(100000, seed++);
    if (tls13) {
      p.key_update(true);
      ++c.key_updates;
      ++c.requested;
    }
    p.write(65536 + 3, seed++);
  }
  p.write(1, seed++);
  p.close_notify();
  return c;
}

bool all_of_value(std::span<std::uint8_t const> s, std::uint8_t v)
{
  return std::all_of(s.begin(), s.end(), [v](std::uint8_t x) { return x == v; });
}


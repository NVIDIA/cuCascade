using bytes = std::vector<std::uint8_t>;

bytes hex(std::string_view h)
{
  auto v = [](char c) -> int {
    if (c >= '0' && c <= '9') { return c - '0'; }
    if (c >= 'a' && c <= 'f') { return c - 'a' + 10; }
    return c - 'A' + 10;
  };
  bytes out;
  for (std::size_t i = 0; i + 1 < h.size(); i += 2) {
    out.push_back(static_cast<std::uint8_t>((v(h[i]) << 4) | v(h[i + 1])));
  }
  return out;
}

bytes operator+(bytes a, bytes const& b)
{
  a.insert(a.end(), b.begin(), b.end());
  return a;
}

/// Append a record.  Unlike `a + f() + g()` (operands unsequenced), `w << f() << g()` evaluates
/// left to right (C++17 [expr.shift]), which matters for sealers that bump a sequence number.
bytes& operator<<(bytes& w, bytes const& r)
{
  w.insert(w.end(), r.begin(), r.end());
  return w;
}

std::span<std::uint8_t const> cs(bytes const& b) { return {b.data(), b.size()}; }

/// Vector equality without Catch2 printing kilobytes on a mismatch.
bool same(bytes const& a, bytes const& b)
{
  if (a.size() != b.size()) {
    std::printf("size mismatch: %zu vs %zu\n", a.size(), b.size());
    return false;
  }
  auto const m = std::mismatch(a.begin(), a.end(), b.begin());
  if (m.first == a.end()) { return true; }
  std::printf(
    "first mismatch at %zu of %zu\n", static_cast<std::size_t>(m.first - a.begin()), a.size());
  return false;
}

/// @p b as a ring view wrapped at @p wrap_at (first = [0, w), second = [w, end)).
ciphertext_view view_of(bytes const& b, std::size_t wrap_at = static_cast<std::size_t>(-1))
{
  auto const* p       = reinterpret_cast<std::byte const*>(b.data());
  std::size_t const w = std::min(wrap_at, b.size());
  return {{p, w}, {p + w, b.size() - w}};
}

ciphertext_view drop(ciphertext_view v, std::size_t n)
{
  if (n <= v.first.size()) { return {v.first.subspan(n), v.second}; }
  return {v.second.subspan(n - v.first.size()), {}};
}

bytes pattern(std::size_t n, std::uint64_t seed)
{
  bytes out(n);
  std::mt19937_64 r(seed);
  for (auto& x : out) {
    x = static_cast<std::uint8_t>(r());
  }
  return out;
}

openssl_kdf const& the_kdf()
{
  static openssl_kdf const k;
  return k;
}

/// TLS 1.3 receive keys from a traffic secret (what `session::export_keys` produces).
traffic_keys keys13(std::uint16_t suite, bytes const& secret, std::uint64_t seq = 0)
{
  suite_info const s = suite_of(protocol_version::tls1_3, suite);
  traffic_keys k;
  k.version      = protocol_version::tls1_3;
  k.cipher       = s.cipher;
  k.cipher_suite = suite;
  k.key_len      = s.key_len;
  k.iv_len       = 12;
  k.secret_len   = static_cast<std::uint8_t>(secret.size());
  std::copy(secret.begin(), secret.end(), k.secret.begin());
  if (s.supported() && secret.size() == s.hash_len) {
    REQUIRE_FALSE(tls13_traffic_keys(the_kdf(),
                                     s,
                                     cs(secret),
                                     std::span<std::uint8_t>(k.key.data(), s.key_len),
                                     std::span<std::uint8_t, 12>(k.iv)));
  }
  k.sequence = seq;
  return k;
}

/// TLS 1.2 receive keys (server write key and salt).
traffic_keys keys12(std::uint16_t suite, bytes const& key, bytes const& salt, std::uint64_t seq = 1)
{
  suite_info const s = suite_of(protocol_version::tls1_2, suite);
  traffic_keys k;
  k.version      = protocol_version::tls1_2;
  k.cipher       = s.cipher;
  k.cipher_suite = suite;
  k.key_len      = static_cast<std::uint8_t>(key.size());
  k.iv_len       = 4;
  std::copy(key.begin(), key.end(), k.key.begin());
  std::copy(salt.begin(), salt.end(), k.iv.begin());
  k.sequence = seq;
  return k;
}


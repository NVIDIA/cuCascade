/**
 * A client session of the OpenSSL provider and an OpenSSL server over a socketpair.  After the
 * handshake the client exports its receive keys and the server writes into a memory BIO, so the
 * test controls every record it produces.  `wire` = all server ciphertext after the handshake,
 * `plain` = the application data the server wrote.
 */
class tls_pair {
 public:
  tls_pair(int version, std::string const& suite, int tickets, bool padding = false)
  {
    int fds[2] = {-1, -1};
    REQUIRE(::socketpair(AF_UNIX, SOCK_STREAM | SOCK_NONBLOCK | SOCK_CLOEXEC, 0, fds) == 0);
    _cfd = fds[0];
    _sfd = fds[1];
    config tc;
    tc.ktls        = ktls_mode::disable;
    tc.min_version = version == TLS1_3_VERSION ? version_bound::tls1_3 : version_bound::tls1_2;
    tc.max_version = tc.min_version;
    if (version == TLS1_3_VERSION) {
      tc.ciphersuites = suite;
    } else {
      tc.cipher_list = suite;
    }
    tc.ca_blob = cucascade::test::tls::default_pki().ca.cert_pem;
    _provider  = make_openssl_provider(tc);
    std::error_code ec;
    _client = _provider->new_session(_cfd, {"localhost", 443}, ec);
    REQUIRE(_client != nullptr);

    cucascade::test::tls::server_ctx_options so;
    so.min_version = version;
    so.max_version = version;
    if (version == TLS1_3_VERSION) {
      so.ciphersuites = suite;
    } else {
      so.cipher_list = suite;
    }
    so.num_tickets = tickets;
    _sctx          = cucascade::test::tls::make_server_ctx(cucascade::test::tls::default_pki(), so);
    _server        = SSL_new(_sctx);
    SSL_set_fd(_server, _sfd);
    SSL_set_accept_state(_server);
    if (padding) {
      SSL_set_record_padding_callback(_server, &tls_pair::pad_cb);
      SSL_set_record_padding_callback_arg(_server, &_pad_rng);
    }
    bool cdone = false;
    bool sdone = false;
    for (int i = 0; i < 1000 && !(cdone && sdone); ++i) {
      if (!cdone) {
        auto const st = _client->handshake(ec);
        REQUIRE(st != handshake_status::failed);
        cdone = st == handshake_status::done;
      }
      if (!sdone) {
        ERR_clear_error();
        int const r = SSL_do_handshake(_server);
        if (r == 1) {
          sdone = true;
        } else {
          int const e = SSL_get_error(_server, r);
          REQUIRE((e == SSL_ERROR_WANT_READ || e == SSL_ERROR_WANT_WRITE));
        }
      }
    }
    REQUIRE(cdone);
    REQUIRE(sdone);
    REQUIRE_FALSE(_client->export_keys(direction::receive, rx));
    // Whatever the server already sent after its handshake (TLS 1.3 tickets) sits in the socket.
    std::array<std::uint8_t, 16384> b{};
    for (;;) {
      ssize_t const n = ::recv(_cfd, b.data(), b.size(), 0);
      if (n <= 0) { break; }
      wire.insert(wire.end(), b.data(), b.data() + n);
    }
    _mem = BIO_new(BIO_s_mem());
    SSL_set0_wbio(_server, _mem);  // takes ownership; the socket BIO stays the read BIO
  }
  ~tls_pair()
  {
    _client.reset();
    if (_server != nullptr) { SSL_free(_server); }
    if (_sctx != nullptr) { SSL_CTX_free(_sctx); }
    if (_cfd >= 0) { ::close(_cfd); }
    if (_sfd >= 0) { ::close(_sfd); }
  }
  tls_pair(tls_pair const&)            = delete;
  tls_pair& operator=(tls_pair const&) = delete;

  /// A fresh opener over the exported receive keys (the keys stay with the pair).
  std::unique_ptr<builtin_record_opener> opener() const
  {
    auto o = opener_for(rx.cipher);
    traffic_keys k;
    k.version      = rx.version;
    k.cipher       = rx.cipher;
    k.cipher_suite = rx.cipher_suite;
    k.key_len      = rx.key_len;
    k.iv_len       = rx.iv_len;
    k.secret_len   = rx.secret_len;
    k.key          = rx.key;
    k.iv           = rx.iv;
    k.secret       = rx.secret;
    k.sequence     = rx.sequence;
    REQUIRE_FALSE(o->init(std::move(k)));
    return o;
  }

  void write(std::size_t n, std::uint64_t seed)
  {
    bytes const p = pattern(n, seed);
    std::size_t w = 0;
    REQUIRE(SSL_write_ex(_server, p.data(), p.size(), &w) == 1);
    REQUIRE(w == n);
    plain.insert(plain.end(), p.begin(), p.end());
    collect();
  }
  void ticket()
  {
    REQUIRE(SSL_new_session_ticket(_server) == 1);
    REQUIRE(SSL_do_handshake(_server) == 1);
    collect();
  }
  void key_update(bool requested)
  {
    REQUIRE(SSL_key_update(
              _server, requested ? SSL_KEY_UPDATE_REQUESTED : SSL_KEY_UPDATE_NOT_REQUESTED) == 1);
    REQUIRE(SSL_do_handshake(_server) == 1);
    collect();
  }
  void close_notify()
  {
    (void)SSL_shutdown(_server);
    collect();
  }

  traffic_keys rx;
  bytes wire;
  bytes plain;

 private:
  static std::size_t pad_cb(SSL*, int, std::size_t, void* arg)
  {
    auto* r             = static_cast<std::mt19937_64*>(arg);
    std::size_t const m = (*r)() % 4;
    return m == 0 ? 0 : (*r)() % (m == 3 ? 600 : 64);  // OpenSSL caps it at the record limit
  }
  void collect()
  {
    char* p      = nullptr;
    long const n = BIO_get_mem_data(_mem, &p);
    if (n > 0) { wire.insert(wire.end(), p, p + n); }
    (void)BIO_reset(_mem);
  }

  int _cfd{-1};
  int _sfd{-1};
  std::shared_ptr<provider const> _provider;
  std::unique_ptr<session> _client;
  SSL_CTX* _sctx{nullptr};
  SSL* _server{nullptr};
  BIO* _mem{nullptr};
  std::mt19937_64 _pad_rng{0x7019};
};


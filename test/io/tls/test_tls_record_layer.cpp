/// TLS 1.3 record writer with known keys (EVP directly; independent of the record layer).
class sealer13 {
 public:
  sealer13(std::uint16_t suite_id, bytes secret, std::uint64_t seq = 0)
    : _suite(suite_of(protocol_version::tls1_3, suite_id)), _secret(std::move(secret)), _seq(seq)
  {
    derive();
  }
  ~sealer13() { EVP_CIPHER_CTX_free(_ctx); }
  sealer13(sealer13 const&)            = delete;
  sealer13& operator=(sealer13 const&) = delete;

  /// KeyUpdate on the sending side (the receiver must re-key in step).
  void update()
  {
    REQUIRE_FALSE(tls13_update_secret(the_kdf(), _suite, std::span<std::uint8_t>(_secret)));
    derive();
    _seq = 0;
  }
  /// Seal an inner plaintext given verbatim (content || type || zeros).
  bytes seal_inner(bytes const& inner, std::uint8_t outer = 23, std::uint16_t version = 0x0303)
  {
    std::size_t const len = inner.size() + 16;
    bytes rec{outer,
              static_cast<std::uint8_t>(version >> 8),
              static_cast<std::uint8_t>(version),
              static_cast<std::uint8_t>(len >> 8),
              static_cast<std::uint8_t>(len)};
    std::array<std::uint8_t, 12> nonce = _iv;
    for (std::size_t i = 0; i < 8; ++i) {
      nonce[4 + i] ^= static_cast<std::uint8_t>(_seq >> (56 - 8 * i));
    }
    int outl = 0;
    REQUIRE(EVP_EncryptInit_ex(_ctx, nullptr, nullptr, nullptr, nonce.data()) == 1);
    REQUIRE(EVP_EncryptUpdate(_ctx, nullptr, &outl, rec.data(), 5) == 1);
    bytes ct(inner.size() + 16);
    if (!inner.empty()) {
      REQUIRE(EVP_EncryptUpdate(
                _ctx, ct.data(), &outl, inner.data(), static_cast<int>(inner.size())) == 1);
    }
    REQUIRE(EVP_EncryptFinal_ex(_ctx, ct.data() + inner.size(), &outl) == 1);
    REQUIRE(EVP_CIPHER_CTX_ctrl(_ctx, EVP_CTRL_AEAD_GET_TAG, 16, ct.data() + inner.size()) == 1);
    ++_seq;
    return rec + ct;
  }
  bytes seal(std::uint8_t type, bytes const& content, std::size_t padding = 0)
  {
    bytes inner = content;
    inner.push_back(type);
    inner.resize(inner.size() + padding, 0);
    return seal_inner(inner);
  }
  bytes data(bytes const& content, std::size_t padding = 0) { return seal(23, content, padding); }
  bytes key_update(std::uint8_t value) { return seal(22, bytes{24, 0, 0, 1, value}); }
  bytes alert(std::uint8_t level, std::uint8_t desc) { return seal(21, bytes{level, desc}); }

 private:
  void derive()
  {
    bytes key(_suite.key_len);
    REQUIRE_FALSE(
      tls13_traffic_keys(the_kdf(), _suite, cs(_secret), std::span<std::uint8_t>(key), _iv));
    EVP_CIPHER_CTX_free(_ctx);
    _ctx = EVP_CIPHER_CTX_new();
    REQUIRE(EVP_EncryptInit_ex(
              _ctx,
              _suite.cipher == aead_cipher::aes_128_gcm ? EVP_aes_128_gcm() : EVP_aes_256_gcm(),
              nullptr,
              key.data(),
              nullptr) == 1);
  }
  suite_info _suite;
  bytes _secret;
  std::array<std::uint8_t, 12> _iv{};
  std::uint64_t _seq;
  EVP_CIPHER_CTX* _ctx{nullptr};
};

/// TLS 1.2 AES-GCM record writer (RFC 5288); explicit nonce derived from the sequence number.
class sealer12 {
 public:
  sealer12(bytes key, bytes salt, std::uint64_t seq = 1) : _salt(std::move(salt)), _seq(seq)
  {
    _ctx = EVP_CIPHER_CTX_new();
    REQUIRE(EVP_EncryptInit_ex(_ctx,
                               key.size() == 16 ? EVP_aes_128_gcm() : EVP_aes_256_gcm(),
                               nullptr,
                               key.data(),
                               nullptr) == 1);
  }
  ~sealer12() { EVP_CIPHER_CTX_free(_ctx); }
  sealer12(sealer12 const&)            = delete;
  sealer12& operator=(sealer12 const&) = delete;

  bytes seal(std::uint8_t type, bytes const& content, std::uint16_t version = 0x0303)
  {
    std::array<std::uint8_t, 8> xn{};
    for (std::size_t i = 0; i < 8; ++i) {
      xn[i] = static_cast<std::uint8_t>((_seq * 0x9E3779B97F4A7C15ULL) >> (56 - 8 * i));
    }
    std::array<std::uint8_t, 12> nonce{};
    std::memcpy(nonce.data(), _salt.data(), 4);
    std::memcpy(nonce.data() + 4, xn.data(), 8);
    std::array<std::uint8_t, 13> aad{};
    for (std::size_t i = 0; i < 8; ++i) {
      aad[i] = static_cast<std::uint8_t>(_seq >> (56 - 8 * i));
    }
    aad[8]                = type;
    aad[9]                = 3;
    aad[10]               = 3;
    aad[11]               = static_cast<std::uint8_t>(content.size() >> 8);
    aad[12]               = static_cast<std::uint8_t>(content.size());
    std::size_t const len = 8 + content.size() + 16;
    bytes rec{type,
              static_cast<std::uint8_t>(version >> 8),
              static_cast<std::uint8_t>(version),
              static_cast<std::uint8_t>(len >> 8),
              static_cast<std::uint8_t>(len)};
    rec.insert(rec.end(), xn.begin(), xn.end());
    int outl = 0;
    REQUIRE(EVP_EncryptInit_ex(_ctx, nullptr, nullptr, nullptr, nonce.data()) == 1);
    REQUIRE(EVP_EncryptUpdate(_ctx, nullptr, &outl, aad.data(), 13) == 1);
    bytes ct(content.size() + 16);
    if (!content.empty()) {
      REQUIRE(EVP_EncryptUpdate(
                _ctx, ct.data(), &outl, content.data(), static_cast<int>(content.size())) == 1);
    }
    REQUIRE(EVP_EncryptFinal_ex(_ctx, ct.data() + content.size(), &outl) == 1);
    REQUIRE(EVP_CIPHER_CTX_ctrl(_ctx, EVP_CTRL_AEAD_GET_TAG, 16, ct.data() + content.size()) == 1);
    ++_seq;
    return rec + ct;
  }

 private:
  bytes _salt;
  std::uint64_t _seq;
  EVP_CIPHER_CTX* _ctx{nullptr};
};

